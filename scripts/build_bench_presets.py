"""Write the WIYN Bench spectrograph mode presets (data/config/bench_*.toml).

Rows are the "Available Bench Gratings and Sample Bench Configurations" table at
https://www.wiyn.org/Instruments/wiynbench.html (last modified 2022-07-11):
grating (grooves/mm @ Littrow blaze angle, or VPH), blaze-peak wavelength [A],
order, Bench Spectrograph Camera coverage [A], red-cable spectral resolution [A]
(typical projected fiber image, 2x2 binning) and the grating's peak efficiency
from the "Available Bench Gratings" table (none listed for the VPH gratings).

The 600 @ 10.1 deg, order 1 row is the existing ``bench_r1800`` preset (the
reference-notebook configuration) and is not regenerated. The other modes are
scaled from it: R keeps the table's ratio to that row (R = 1800 at 5500/3.35),
the spectrograph efficiency scales with grating peak efficiency relative to its
72%, and everything else (pixels/resel, QE, detector) is the same placeholder.
Wavelength ranges are clipped to the 400-1800 nm throughput curves; a mode
entirely outside them is skipped.
"""
from pathlib import Path

CONFIG = Path(__file__).resolve().parents[1] / "src/lfast_etc/data/config"
ANCHOR_R, ANCHOR_RES = 1800.0, 5500.0 / 3.35      # bench_r1800 and its table row
ANCHOR_S_OPT, ANCHOR_EFF = 0.3, 72.0
WMIN, WMAX = 400.0, 1800.0

STA1_NOTE = '''# Detector: WIYN STA1 CCD (wiyn.org/Instruments/STA1vsT2KA.html), 18-bit ADC, three gain modes:
#   mode     e-/DN   read noise   ADC limit     binding limit
#   high     0.219   3.2 e-        57,400 e-    ADC (below the 63,000 e- 1% linearity point)
#   medium   0.438   3.7 e-       114,800 e-    full well 87,500 e-
#   low      0.876   4.3 e-       229,600 e-    full well 87,500 e-
# This preset assumes MEDIUM gain (read_noise 3.7, full_well 87,500). For high gain use
# Instrument.from_preset(..., read_noise=3.2, full_well=57400).
'''

# grating label, central A, order, coverage A, red-cable resolution A, peak eff %, note
ROWS = [
    ("316 @ 7.0", 7500, 1, 5290, 5.72, 70, ""),
    ("316 @ 7.0", 3750, 2, 2645, 2.86, 70, ""),
    ("400 @ 4.2", 5000, 1, 4199, 4.56, 70, "not recommended by WIYN: hard to focus over the range"),
    ("600 @ 13.9", 7500, 1, 2724, 2.86, 70, ""),
    ("600 @ 13.9", 3800, 2, 1362, 1.43, 70, ""),
    ("860 @ 30.9", 10800, 1, 1680, 1.64, 65, ""),
    ("860 @ 30.9", 6000, 2, 840, 0.77, 65, ""),
    ("860 @ 30.9", 4000, 3, 560, 0.52, 65, ""),
    ("1200 @ 28.7", 7500, 1, 1231, 1.19, 55, ""),
    ("1200 @ 28.7", 4000, 2, 615, 0.58, 55, ""),
    ("316 @ 63.4", 6563, 9, 250, 0.23, 50, ""),
    ("316 @ 63.4", 3890, 14, 215, 0.19, 50, ""),
    ("740 VPH", 8798, 1, 2152, 2.68, None, ""),
    ("740 VPH", 5000, 2, 1076, 1.34, None, ""),
    ("3300 VPH", 5120, 1, 273, 0.31, None, ""),
]


def preset_name(grating, order):
    g = grating.replace(" @ ", "_").replace(".", "p").replace(" VPH", "vph").lower()
    return f"bench_{g}_o{order}"


def main():
    for grating, central, order, coverage, res, eff, note in ROWS:
        lo = max(WMIN, (central - coverage / 2) / 10)
        hi = min(WMAX, (central + coverage / 2) / 10)
        clipped = lo > (central - coverage / 2) / 10 + 1e-9
        if hi <= lo:   # 316 @ 63.4 order 14 (378-400 nm) lies entirely below the throughput curves
            print(f"skip {grating} order {order}: {central} A is below the {WMIN:.0f} nm throughput floor")
            continue
        r = ANCHOR_R * (central / res) / ANCHOR_RES
        s_opt = ANCHOR_S_OPT * (eff / ANCHOR_EFF if eff else 1.0)
        name = preset_name(grating, order)
        desc = f"WIYN Bench, {grating.replace(' @ ', ' @ ')}{'' if 'VPH' in grating else ' deg'}, order {order}, {lo:.0f}-{hi:.0f} nm, R~{round(r, -1):.0f}"
        if clipped:
            desc += " (clipped at 400 nm)"
        if note:
            desc += f" ({note})"
        eff_line = f"# grating peak efficiency {eff}% vs 72% for the 600 @ 10.1 anchor" if eff else \
            "# no peak efficiency listed for the VPH gratings: anchor value kept"
        text = f"""# WIYN Bench spectrograph, {grating} grating, order {order}, blaze peak {central} A.
# Row of https://www.wiyn.org/Instruments/wiynbench.html; generated by
# scripts/build_bench_presets.py from the bench_r1800 anchor (see that script).
# Table coverage {coverage} A, red-cable resolution {res} A at 2x2 binning.
[instrument]
name = "{name}"
description = "{desc}"
wavelength_min_nm = {lo:.1f}
wavelength_max_nm = {hi:.1f}
resolving_power = {r:.0f}
pixels_per_resel = 2.2    # dispersion direction only, as bench_r1800
spectrograph_efficiency = {s_opt:.3f}  {eff_line}
slit_throughput = 1.0
qe = 0.75              # placeholder flat QE, as bench_r1800
dark_current = 3.0e-4  # e-/s/pix
{STA1_NOTE}read_noise = 3.7       # e-/pix, STA1 medium gain
full_well = 87500.0    # e-/pix, STA1 full well (medium gain; 1% linearity to 63,000 e-)
min_exptime = 1.0
"""
        (CONFIG / f"{name}.toml").write_text(text)
        print(f"{name:24s} {lo:7.1f}-{hi:7.1f} nm  R={r:7.0f}  S_opt={s_opt:.3f}")


if __name__ == "__main__":
    main()
